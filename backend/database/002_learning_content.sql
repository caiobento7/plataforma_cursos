create table if not exists public.course_modules (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  title text not null,
  sort_order integer not null default 0 check (sort_order >= 0),
  unique (course_id, sort_order)
);

create table if not exists public.lessons (
  id bigint generated by default as identity primary key,
  module_id bigint not null references public.course_modules(id) on delete cascade,
  title text not null,
  duration text not null,
  content_type text not null check (content_type in ('video', 'quiz')),
  video_url text,
  document_url text,
  sort_order integer not null default 0 check (sort_order >= 0),
  unique (module_id, sort_order)
);

create table if not exists public.quizzes (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null unique references public.lessons(id) on delete cascade,
  pass_mark integer not null default 70 check (pass_mark between 0 and 100)
);

create table if not exists public.quiz_questions (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  question_text text not null,
  options jsonb not null,
  correct_answer text not null,
  sort_order integer not null default 0 check (sort_order >= 0),
  unique (quiz_id, sort_order)
);

create table if not exists public.lesson_progress (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  completed boolean not null default false,
  completed_at timestamptz,
  unique (student_id, lesson_id)
);

create table if not exists public.lesson_questions (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  author_id uuid not null references public.profiles(id) on delete cascade,
  question_text text not null,
  answer_text text,
  answered_by uuid references public.profiles(id) on delete set null,
  answered_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.course_modules enable row level security;
alter table public.lessons enable row level security;
alter table public.quizzes enable row level security;
alter table public.quiz_questions enable row level security;
alter table public.lesson_progress enable row level security;
alter table public.lesson_questions enable row level security;
